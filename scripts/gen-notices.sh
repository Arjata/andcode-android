#!/usr/bin/env bash
# gen-notices.sh — Generate THIRD-PARTY-NOTICES.md from bundle/manifest (NAMING §7.2 / REUSE §4)
# Usage: gen-notices.sh <manifest> [> output.md]
set -euo pipefail
MF="${1:?usage: gen-notices.sh <manifest>}"

cat <<'HEAD'
# THIRD-PARTY NOTICES

Third-party components included in this distribution (andcode) and their licensing information.
The project itself is licensed under AGPL-3.0-only (see the repository LICENSE). Refer to the listed
upstream repositories for full license texts. GPL-2.0 components (busybox, proot) are distributed as
**aggregated independent programs**; source locations are listed below.

## Component inventory

| Logical path | Physical name (Tier P) | Kind | License | Version | Upstream |
|---|---|---|---|---|---|
HEAD

# Skip comment lines; sort output by license and upstream.
grep -v '^#' "$MF" | grep -v '^$' | sort -t$'\t' -k4,4 -k6,6 | \
  awk -F'\t' '{ gsub(/\|/, "\\|", $1); gsub(/\|/, "\\|", $2);
    printf "| %s | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6 }'

cat <<'FOOT'

## License highlights

- **MIT / Apache-2.0 / BSD-2-Clause components** (opencode, dropbear, jackpal,
  libandroid-shmem, etc.): distributed with copyright and license notices retained.
- **LGPL components** (glibc, libtalloc): distributed in the bundle; corresponding source is available upstream
  (glibc 2.39: sourceware.org; libtalloc: samba.org).
- **GPL-2.0 components** (busybox, proot): distributed unmodified as aggregated independent programs;
  source: busybox.net (1.36.1, Alpine busybox-static build and
  github.com/proot-me/proot), github.com/proot-me/proot.
- Original project components (shim, launcher, wrappers, entry scripts, APK) are provided under AGPL-3.0-only;
  see the accompanying LICENSE for the full text.

Generated by `scripts/gen-notices.sh` (automatically in CI; do not edit this file manually).
FOOT
